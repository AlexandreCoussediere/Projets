const select=document.getElementById("chapitre");

Object.keys(chapitres).forEach(c=>{

let option=document.createElement("option");

option.value=c;

option.textContent=c;

select.appendChild(option);

});

let liste=[];

let index=0;

let score=0;

function melanger(t){

return t.sort(()=>Math.random()-0.5);

}

document.getElementById("start").onclick=()=>{

liste=melanger([...chapitres[select.value]]);

index=0;

score=0;

document.getElementById("quiz").classList.remove("hidden");

question();

}

function question(){

document.getElementById("resultat").textContent="";

document.getElementById("reponse").value="";

let q=liste[index];

document.getElementById("titre").textContent=q.question;

document.getElementById("typeDate").textContent="Type attendu : "+q.type;

document.getElementById("score").textContent=

"Score : "+score+" / "+liste.length;

}

document.getElementById("valider").onclick=()=>{

let rep=document.getElementById("reponse").value

.toLowerCase()

.trim();

let bonne=liste[index].reponse

.toLowerCase();

if(rep===bonne){

score++;

document.getElementById("resultat").textContent="✔ Bonne réponse";

}else{

document.getElementById("resultat").textContent=

"❌ Faux : "+liste[index].reponse;

}

index++;

if(index<liste.length){

setTimeout(question,1200);

}else{

setTimeout(()=>{

alert("Terminé ! Score : "+score+"/"+liste.length);

},500);

}

}

document.getElementById("voir").onclick=()=>{

document.getElementById("resultat").textContent=

"Réponse : "+liste[index].reponse;

}